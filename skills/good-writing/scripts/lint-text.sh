#!/usr/bin/env bash
# Линтер механических антипаттернов из skills/good-writing/antipatterns.md.
# Использование: scripts/lint-text.sh путь/к/draft.md
#
# Ловит только то, что ищется поиском по шаблону. Вкусовые решения
# остаются за автором. Каждая находка — повод посмотреть на место
# в тексте, а не приговор: ложные срабатывания нормальны.

set -u

# Без UTF-8 локали grep сравнивает кириллицу побайтово и дает ложные срабатывания
export LC_ALL=en_US.UTF-8

if [ $# -lt 1 ] || [ ! -f "${1:-}" ]; then
  echo "Использование: scripts/lint-text.sh <файл.md>"
  exit 2
fi

FILE="$1"
TOTAL=0

# Буква «е с двумя точками» собирается из кода символа, чтобы не
# появляться в файлах системы напрямую (см. docs/customization.md).
YO=$(printf '\xd1\x91')
YO_UP=$(printf '\xd0\x81')

check() { # check "заголовок" "grep-шаблон" [флаги grep]
  local title="$1" pattern="$2" flags="${3:--nE}"
  local hits n
  hits=$(grep $flags "$pattern" "$FILE" 2>/dev/null || true)
  if [ -n "$hits" ]; then
    n=$(printf '%s\n' "$hits" | wc -l | tr -d ' ')
    echo
    echo "== $title ($n)"
    printf '%s\n' "$hits"
    TOTAL=$((TOTAL + n))
  fi
}

# Буква ищется как точная байтовая строка — работает в любой локали
YO_HITS=$(grep -nF -e "$YO" -e "$YO_UP" "$FILE" 2>/dev/null || true)
if [ -n "$YO_HITS" ]; then
  N=$(printf '%s\n' "$YO_HITS" | wc -l | tr -d ' ')
  echo
  echo "== Буква с двумя точками ($N)"
  printf '%s\n' "$YO_HITS"
  TOTAL=$((TOTAL + N))
fi

check "Краткие причастия — проверь, не сказуемое ли" \
  "(выбран|выбрана|выбрано|выбраны|собран|собрана|собрано|собраны|задан|задана|задано|заданы|сверстан|сверстана|сверстано|построен|построена|построено|настроен|настроена|настроено|создан|создана|создано|созданы|получен|получена|получено|установлен|установлена|установлено)" \
  "-wnE"

check "Связочные глаголы — заменить конкретным глаголом" \
  "(является|являются|представляет собой|представляют собой|служит|служат)" \
  "-wnE"

check "Вводные и штампы нейротекста" \
  "(В современном мире|Все мы знаем|В эпоху |Стоит отметить|Важно понимать|Важно отметить|В заключение|Это позволяет|отличн(ое|ым) решени|Данн(ый|ая|ое|ые) )"

check "Пустые усиления" \
  "(невероятно|исключительно|поистине|идеально подходит|незаменим)"

check "Канцелярит" \
  "(в рамках|с целью|в целях|посредством|осуществля|производится|реализуется|в настоящее время)"

check "Две и больше вопросительных в одной строке — стаккато вопросов" \
  '\?[^?]*\?'

check "Проценты — проверь, есть ли рядом абсолютные числа" \
  '[0-9]+ ?%'

# Незакрытые плейсхолдеры — блокирующая проверка перед финализацией
PLACEHOLDERS=$(grep -nE '(URL-не-найден|URL-TODO|\[Вставить|\[ссылка\]|\[TODO|, в работе\]|\[в работе|\[уточнить|уточнить\]|\[скоро|\[будет|XXX)' "$FILE" 2>/dev/null || true)
if [ -n "$PLACEHOLDERS" ]; then
  N=$(printf '%s\n' "$PLACEHOLDERS" | wc -l | tr -d ' ')
  echo
  echo "== БЛОКЕР: незакрытые плейсхолдеры ($N) — текст нельзя финализировать"
  printf '%s\n' "$PLACEHOLDERS"
  TOTAL=$((TOTAL + N))
fi

# Противопоставления «не X, а Y» — счетчик с порогом
NOTX=$(grep -cE '(, а не |это не [^.]*, (это|а) )' "$FILE" 2>/dev/null || true)
NOTX=${NOTX:-0}
if [ "$NOTX" -gt 2 ]; then
  echo
  echo "== Противопоставлений «не X, а Y»: $NOTX (порог — 2 на текст)"
  grep -nE '(, а не |это не [^.]*, (это|а) )' "$FILE" || true
  TOTAL=$((TOTAL + NOTX))
fi

# Плотность тире — только сводка, без списка строк
DASHES=$(grep -o '—' "$FILE" | wc -l | tr -d ' ')
LINES=$(grep -c '' "$FILE" | tr -d ' ')
if [ "$DASHES" -gt $((LINES / 5 + 3)) ]; then
  echo
  echo "== Тире: $DASHES на $LINES строк — много. Правило: минимум тире, переформулируй."
  TOTAL=$((TOTAL + 1))
fi

echo
if [ "$TOTAL" -eq 0 ]; then
  echo "Механических антипаттернов не найдено. Вкусовые проверки все равно нужны."
else
  echo "Итого подозрительных мест: $TOTAL. Разбери каждое: правь или осознанно оставляй."
fi
exit 0
